function isEnglish() {
  return localeGetter() === 'en-US'
}

function applyPattern(text) {
  for (const [pattern, replacement] of EN_PATTERNS) {
    if (pattern.test(text)) {
      return typeof replacement === 'function'
        ? text.replace(pattern, replacement)
        : text.replace(pattern, replacement)
    }
  }
  return ''
}

export function translateText(text) {
  if (typeof text !== 'string') {
    return text
  }
  const raw = text.trim()
  if (!raw) {
    return text
  }

  const exact = EN_TEXT[raw]
  const translated = exact || applyPattern(raw)
  if (translated) {
    return text.replace(raw, translated)
  }

  return text
}

export function translateApiMessage(message) {
  if (!isEnglish() || typeof message !== 'string') {
    return message
  }
  return translateText(message)
}

function translateTextNode(node) {
  if (!node.nodeValue || !/[\u4e00-\u9fff]/.test(node.nodeValue)) {
    if (!isEnglish() && TRANSLATED_TEXT_NODES.has(node)) {
      node.nodeValue = TRANSLATED_TEXT_NODES.get(node)
      TRANSLATED_TEXT_NODES.delete(node)
    }
    return
  }

  if (!isEnglish()) {
    if (TRANSLATED_TEXT_NODES.has(node)) {
      node.nodeValue = TRANSLATED_TEXT_NODES.get(node)
      TRANSLATED_TEXT_NODES.delete(node)
    }
    return
  }

  const original = TRANSLATED_TEXT_NODES.get(node) || node.nodeValue
  const translated = translateText(original)
  if (translated !== original) {
    TRANSLATED_TEXT_NODES.set(node, original)
    node.nodeValue = translated
  }
}

function translateElementAttributes(el) {
  ATTRIBUTE_NAMES.forEach(name => {
    if (!el.hasAttribute(name)) {
      return
    }

    let originals = TRANSLATED_ATTRIBUTES.get(el)
    if (!isEnglish()) {
      if (originals?.has(name)) {
        el.setAttribute(name, originals.get(name))
        originals.delete(name)
      }
      return
    }

    const value = originals?.get(name) || el.getAttribute(name)
    if (!value || !/[\u4e00-\u9fff]/.test(value)) {
      return
    }

    const translated = translateText(value)
    if (translated !== value) {
      if (!originals) {
        originals = new Map()
        TRANSLATED_ATTRIBUTES.set(el, originals)
      }
      originals.set(name, value)
      el.setAttribute(name, translated)
    }
  })
}

function shouldTranslateControlValue(el) {
  const tag = el.tagName
  if (tag !== 'INPUT' && tag !== 'TEXTAREA') {
    return false
  }

  return el.readOnly ||
    el.disabled ||
    el.closest('.el-select') ||
    el.closest('.el-cascader') ||
    el.classList.contains('el-select__input')
}

function translateControlValue(el) {
  if (!shouldTranslateControlValue(el)) {
    return
  }

  const cached = TRANSLATED_CONTROL_VALUES.get(el)

  if (!isEnglish()) {
    if (cached && el.value === cached.translated) {
      el.value = cached.original
    }
    TRANSLATED_CONTROL_VALUES.delete(el)
    return
  }

  const currentValue = String(el.value || '')
  if (!currentValue) {
    return
  }

  const original = /[\u4e00-\u9fff]/.test(currentValue)
    ? currentValue
    : cached?.original

  if (!original || !/[\u4e00-\u9fff]/.test(original)) {
    return
  }

  const translated = translateText(original)
  if (translated && translated !== original && el.value !== translated) {
    TRANSLATED_CONTROL_VALUES.set(el, { original, translated })
    el.value = translated
  }
}

function shouldSkipElement(node) {
  const tag = node.tagName
  return tag === 'SCRIPT' || tag === 'STYLE' || tag === 'NOSCRIPT'
}

function normalizeNode(node) {
  if (!node) {
    return
  }

  if (node.nodeType === Node.TEXT_NODE) {
    translateTextNode(node)
    return
  }

  if (node.nodeType !== Node.ELEMENT_NODE || shouldSkipElement(node)) {
    return
  }

  translateElementAttributes(node)
  translateControlValue(node)
  Array.from(node.childNodes).forEach(normalizeNode)
}

export function refreshI18nNormalizer() {
  if (scheduled) {
    return
  }
  scheduled = true
  window.requestAnimationFrame(() => {
    scheduled = false
    normalizeNode(document.body)
  })
}

function refreshAfterInteraction() {
  refreshI18nNormalizer()
  window.setTimeout(refreshI18nNormalizer, 0)
  window.setTimeout(refreshI18nNormalizer, 50)
}

function patchLocalStorage(languageKey) {
  if (storagePatched) {
    return
  }

  const storagePrototype = Object.getPrototypeOf(window.localStorage)
  const originalSetItem = storagePrototype.setItem
  storagePrototype.setItem = function setItem(key, value) {
    originalSetItem.call(this, key, value)
    if (key === languageKey) {
      window.dispatchEvent(new CustomEvent('boer-language-change', { detail: { language: value } }))
      refreshI18nNormalizer()
    }
  }
  storagePatched = true
}

export function installI18nNormalizer(Vue, options = {}) {
  localeGetter = options.localeGetter || localeGetter
  const languageKey = options.languageKey || 'language'

  Vue.prototype.$translateText = (value) => (isEnglish() ? translateText(value) : value)
  Vue.prototype.$translateApiMessage = translateApiMessage

  if (installed || typeof window === 'undefined') {
    return
  }

  installed = true
  patchLocalStorage(languageKey)
  window.addEventListener('boer-language-change', refreshI18nNormalizer)
  document.addEventListener('click', refreshAfterInteraction, true)
  document.addEventListener('change', refreshAfterInteraction, true)

  observer = new MutationObserver(() => refreshI18nNormalizer())
  observer.observe(document.documentElement, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ATTRIBUTE_NAMES
  })

  refreshI18nNormalizer()
}
